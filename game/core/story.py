def campaigns_for(level_id: str, is_first: bool, seen: callable) -> list[Line]:
    """Собирает сцены перед боем.

    ``seen(key)`` сообщает, видел ли игрок уже эту сцену. Вступление
    показывается только с первой картой кампании, брифинг — один раз на
    каждую карту.
    """
    scenes: list[Line] = []
    if is_first and not seen("intro"):
        scenes.extend(INTRO)
    briefing = BRIEFINGS.get(level_id)
    if briefing and not seen(f"brief:{level_id}"):
        scenes.extend(briefing)
    return scenes


def epilogue_for(level_id: str, seen: callable) -> list[Line]:
    """Сцены после победы: эпилог карты и развязка после цитадели."""
    scenes: list[Line] = []
    epilogue = EPILOGUES.get(level_id)
    if epilogue and not seen(f"epi:{level_id}"):
        scenes.extend(epilogue)
    if level_id == CITADEL_ID and not seen("finale"):
        scenes.extend(FINALE)
    return scenes


