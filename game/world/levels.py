"""Карты-уровни: база, площадки, дороги врагов и сложность."""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass
class Level:
    """Одна карта со своим расположением базы и маршрутами врагов."""

    id: str
    name: str
    subtitle: str
    desc: str
    world_w: float
    world_h: float
    base_pos: tuple[float, float]
    slots: list[tuple[float, float]]
    routes: list[list[tuple[float, float]]]
    gold_spots: list[tuple[float, float]]
    waves: int
    difficulty: float
    start_gold: int
    base_hp: int
    ground: tuple
    ground_dark: tuple
    ground_light: tuple
    seed: int
    trees: int
    accent: tuple = (0.16, 0.55, 0.30, 1)
    first_delay: float = 22.0
    wave_pause: float = 13.0
    landmarks: list[tuple[float, float]] = field(default_factory=list)
    # Сколько «дикой» земли добавить по бокам (x) и в длину (y).
    # Карта перестаёт упираться в стену сразу за базой и дорогами.
    expand: tuple[float, float] = (0.0, 0.0)
    # Обучающая карта: короткая, с подсказками, ведёт на первую настоящую карту.
    tutorial: bool = False
    # Какой босс приходит на последней волне. Финальные карты могут
    # подставлять своего, более сильного.
    boss_kind: str = "boss"
    # Крупные золотые жилы: на них лежат монеты по 30 золота.
    rich_spots: list[tuple[float, float]] = field(default_factory=list)


